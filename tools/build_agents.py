#!/usr/bin/env python3
"""Generate plugins/<plugin>/agents/<name>.md from shared/agents/.

shared/agents/variants.json is a list of
    {"plugin", "name", "body", "description", "model", "effort",
     "tools": [...], "color"?}
where body names shared/agents/<body>.body.md. Several variants may share
one body, so a role's text is written once.

    python3 tools/build_agents.py          write the agent files
    python3 tools/build_agents.py --check  exit 1 listing drifted files

A generated file that no variant produces any more counts as drift too.
Repo-maintenance only; users never run it.
"""

import argparse
import glob
import json
import os
import sys

KIT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = ("<!-- generated by tools/build_agents.py from shared/agents/%s.body.md; "
          "edit the source -->")
MARKER = "<!-- generated by tools/build_agents.py"
REQUIRED = ("plugin", "name", "body", "description", "model", "effort", "tools")


def _yaml_str(value):
    # A JSON string is a valid YAML double-quoted scalar.
    return json.dumps(value, ensure_ascii=False)


def render(variant, body):
    lines = ["---",
             "name: %s" % variant["name"],
             "description: %s" % _yaml_str(variant["description"]),
             "model: %s" % variant["model"],
             "effort: %s" % variant["effort"]]
    # An empty tools list leaves the field out, so the agent inherits every
    # tool the session has (an empty "tools:" value would be ambiguous).
    if variant["tools"]:
        lines.insert(3, "tools: %s" % ", ".join(variant["tools"]))
    if variant.get("color"):
        lines.append("color: %s" % variant["color"])
    lines += ["---", HEADER % variant["body"], ""]
    return "\n".join(lines) + "\n" + body.rstrip("\n") + "\n"


def expected_files(kit):
    with open(os.path.join(kit, "shared", "agents", "variants.json"), encoding="utf-8") as fh:
        variants = json.load(fh)
    if not isinstance(variants, list):
        raise SystemExit("variants.json: expected a list")
    out = {}
    for n, variant in enumerate(variants):
        missing = [k for k in REQUIRED if k not in variant]
        if missing:
            raise SystemExit("variants.json[%d]: missing %s" % (n, ", ".join(missing)))
        body_path = os.path.join(kit, "shared", "agents", "%s.body.md" % variant["body"])
        with open(body_path, encoding="utf-8") as fh:
            body = fh.read()
        rel = os.path.join("plugins", variant["plugin"], "agents", "%s.md" % variant["name"])
        if rel in out:
            raise SystemExit("variants.json: %s produced twice" % rel)
        out[rel] = render(variant, body)
    return out


def generated_on_disk(kit):
    found = set()
    for path in glob.glob(os.path.join(kit, "plugins", "*", "agents", "*.md")):
        with open(path, encoding="utf-8") as fh:
            if MARKER in fh.read():
                found.add(os.path.relpath(path, kit))
    return found


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report drift, write nothing")
    parser.add_argument("--kit", default=KIT, help="kit root (default: this kit)")
    args = parser.parse_args(argv)
    want = expected_files(args.kit)
    drift = []
    for rel, text in sorted(want.items()):
        path = os.path.join(args.kit, rel)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                current = fh.read()
        if current == text:
            continue
        if args.check:
            drift.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)
            print("wrote %s" % rel)
    for rel in sorted(generated_on_disk(args.kit) - set(want)):
        if args.check:
            drift.append(rel + " (no variant produces it)")
        else:
            os.remove(os.path.join(args.kit, rel))
            print("removed %s" % rel)
    if drift:
        print("generated agents out of date (run tools/build_agents.py):", file=sys.stderr)
        for rel in drift:
            print("  %s" % rel, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
